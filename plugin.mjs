#!/usr/bin/env node
// Clockwork as a Claude Code plugin: writes the plugin's files from the kit, so they never drift from it.
// Usage: node plugin.mjs           write .claude-plugin/plugin.json and skills/onboard/SKILL.md
//        node plugin.mjs --check   exit 1 if either is out of date (test/plugin.test.mjs runs this)
// The plugin root is the kit folder itself (the published repo's root). It carries one skill, /clockwork:onboard: the
// same onboarding skill `install.mjs --global-skill` copies, with KIT defaulting to ${CLAUDE_PLUGIN_ROOT}, which Claude
// Code substitutes in plugin skills (docs code.claude.com/docs/en/skills, "String substitutions", read 2026-10-14).
// Hooks stay per project: the skill installs them into the project, so a plugin install changes no other project.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const KIT = path.dirname(fileURLToPath(import.meta.url));
const version = fs.readFileSync(path.join(KIT, 'VERSION'), 'utf8').trim();
const PLACEHOLDER = '/path/to/clockwork';

export function pluginSkill(src) {
  if (!src.includes(`KIT="\${CLOCKWORK_KIT:-${PLACEHOLDER}}"`)) throw new Error(`onboard/SKILL.md has no KIT="\${CLOCKWORK_KIT:-${PLACEHOLDER}}" line`);
  return src
    .replace(/^name: clockwork-onboard$/m, 'name: onboard')
    .replaceAll('/clockwork-onboard', '/clockwork:onboard')
    .replace('else `/path/to/clockwork` (`install.mjs --global-skill` writes the real kit path there)', 'else this plugin\'s folder, `${CLAUDE_PLUGIN_ROOT}`')
    .replaceAll(PLACEHOLDER, '${CLAUDE_PLUGIN_ROOT}')
    .replace(/^(<!-- Frontmatter keys)/m, '<!-- Generated by plugin.mjs from onboard/SKILL.md. Edit that file, then run node plugin.mjs. -->\n$1');
}

export const manifest = () => ({
  name: 'clockwork',
  displayName: 'Clockwork',
  version,
  description: 'Run several Claude Code sessions on one project without them overwriting each other\'s work. /clockwork:onboard installs the hooks, task registry and rules into a project.',
  author: { name: 'Mary Kovziridze' },
  homepage: 'https://github.com/marykovziridze/clockwork',
  repository: 'https://github.com/marykovziridze/clockwork',
  license: 'MIT',
  keywords: ['parallel-sessions', 'hooks', 'git', 'worktrees', 'overnight', 'task-registry'],
});

const want = {
  '.claude-plugin/plugin.json': JSON.stringify(manifest(), null, 2) + '\n',
  'skills/onboard/SKILL.md': pluginSkill(fs.readFileSync(path.join(KIT, 'onboard', 'SKILL.md'), 'utf8')),
};

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  const stale = Object.entries(want).filter(([rel, text]) => { try { return fs.readFileSync(path.join(KIT, rel), 'utf8') !== text; } catch { return true; } }).map(([rel]) => rel);
  if (process.argv.includes('--check')) {
    console.log(stale.length ? `ERR out of date: ${stale.join(', ')}; run node plugin.mjs` : 'OK plugin files current');
    process.exit(stale.length ? 1 : 0);
  }
  for (const [rel, text] of Object.entries(want)) { fs.mkdirSync(path.dirname(path.join(KIT, rel)), { recursive: true }); fs.writeFileSync(path.join(KIT, rel), text); }
  console.log(`OK wrote ${Object.keys(want).join(', ')} (Clockwork ${version})`);
}
